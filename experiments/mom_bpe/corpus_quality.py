"""Independent language, script, Unicode and text-quality measurements."""

import re
import unicodedata
from collections import Counter
from pathlib import Path
from urllib.parse import urlsplit, urlunsplit

import regex

from experiments.mom_bpe.diagnose import sha

MAL_LETTER = regex.compile(r"[\p{L}&&\p{Script=Malayalam}]", regex.V1)
LATIN_LETTER = regex.compile(r"[\p{L}&&\p{Script=Latin}]", regex.V1)
LETTER = regex.compile(r"\p{L}")
MAL_WORD = regex.compile(r"[\p{Script=Malayalam}\u200c\u200d]+")
MAL_MARK = regex.compile(r"[\p{Script=Malayalam}&&\p{M}]", regex.V1)
CHILLU = re.compile(r"[\u0d7a-\u0d7f\u0d54-\u0d56]")
LEGACY_CHILLU = re.compile(r"[\u0d23\u0d28\u0d30\u0d32\u0d33]\u0d4d\u200d")
HTML = re.compile(r"</?(?:div|span|p|html|script|a|br|img|li|table)\b[^>]{0,256}>|&(?:nbsp|amp|lt|gt);", re.I)
CODE = re.compile(r"(?:<\|im_(?:start|end)\|>|\b(?:as an AI language model|machine translated|generated by chatgpt)\b)", re.I)
URL = re.compile(r"https?://\S+", re.I)
HISTORICAL = "\u0d00\u0d3b\u0d3c\u0d4e\u0d54\u0d55\u0d56"


class FastTextLanguage:
    """Measure short document windows with the pinned official 176-label model."""

    def __init__(self, path, expected_sha256):
        import fasttext

        path = Path(path)
        if sha(path.read_bytes()) != expected_sha256:
            raise ValueError("Language model SHA-256 mismatch")
        self.model = fasttext.load_model(str(path))
        self.label_count = len(self.model.get_labels())

    def __call__(self, text):
        clean = " ".join(text.split())
        starts = sorted({0, max(0, len(clean) // 2 - 256), max(0, len(clean) - 512)})
        counts, scores = Counter(), []
        for start in starts:
            window = clean[start:start + 512]
            if len(LETTER.findall(window)) < 20:
                continue
            # The Windows 0.9.2 wrapper's NumPy array conversion is incompatible
            # with NumPy 2. Its compiled predictor returns ranked tuples directly.
            result = self.model.f.predict(window + "\n", self.label_count, 0.0, "strict")
            probs = {label.removeprefix("__label__"): float(prob) for prob, label in result}
            if result:
                counts[result[0][1].removeprefix("__label__")] += 1
                scores.append(min(1.0, probs.get("ml", 0.0)))
        return {"windows": len(scores), "top_languages": dict(counts),
                "ml_score": sum(scores) / len(scores) if scores else None,
                "non_ml_windows": len(scores) - counts["ml"]}


def duplicate_view(text):
    # This comparison-only view never replaces source or training text.
    return " ".join(unicodedata.normalize("NFC", text).split())


def script_metrics(text):
    return {"letters": len(LETTER.findall(text)), "malayalam_letters": len(MAL_LETTER.findall(text)),
            "latin_letters": len(LATIN_LETTER.findall(text))}


def unicode_metrics(text):
    unattached = 0
    has_base = False
    for char in text:
        if MAL_LETTER.fullmatch(char):
            has_base = True
        elif MAL_MARK.fullmatch(char):
            unattached += not has_base
        elif char not in "\u200c\u200d":
            has_base = False
    return {"replacement_chars": text.count("\ufffd"), "unattached_ml_marks": unattached,
            "control_chars": sum(unicodedata.category(c) == "Cc" and c not in "\r\n\t" for c in text),
            "atomic_chillus": len(CHILLU.findall(text)), "legacy_chillu_patterns": len(LEGACY_CHILLU.findall(text)),
            "virama": text.count("\u0d4d"), "repeated_virama": text.count("\u0d4d\u0d4d"),
            "historical_chars": sum(c in HISTORICAL for c in text),
            "zwj": text.count("\u200d"), "zwnj": text.count("\u200c")}


def boilerplate_metrics(text):
    lines = Counter(duplicate_view(line) for line in text.splitlines() if len(line.strip()) >= 20)
    return {"repeated_line_hits": sum(n - 1 for n in lines.values()), "html_hits": len(HTML.findall(text)),
            "url_hits": len(URL.findall(text)), "synthetic_proxy_hits": len(CODE.findall(text))}


def words(text):
    for word in MAL_WORD.findall(text):
        if MAL_LETTER.search(word):
            yield word


def profile(raw, canonical, language=None):
    result = {"raw_bytes": len(raw.encode("utf-8")), "canonical_bytes": len(canonical.encode("utf-8")),
              "chars": len(raw), "canonical_changed": raw != canonical}
    for check in (script_metrics, unicode_metrics, boilerplate_metrics):
        result.update(check(raw))
    result["language"] = language(raw) if language is not None else None
    return result


def page_group(attributes):
    """Canonicalize known URLs conservatively for source-ancestry grouping."""
    url = attributes.get("url") or attributes.get("document_url")
    if not isinstance(url, str):
        return None, None
    try:
        parsed = urlsplit(url)
        host = parsed.hostname
    except ValueError:
        return None, None
    if parsed.scheme not in ("http", "https") or not host or parsed.username or parsed.password:
        return None, None
    # Preserve paths and queries. Removing query parameters can join different articles.
    return urlunsplit(("https", parsed.netloc.casefold(), parsed.path or "/", parsed.query, "")), host


def morphological_summary(counts, analyzer, limit=150):
    selected = sorted((w for w in counts if len(w) <= 48), key=lambda w: (sha(w.encode()), w))[:limit]
    tags, recognized, multiple = set(), 0, 0
    for text in selected:
        readings = analyzer.analyse(text, foreign_word_check=False)
        recognized += bool(readings)
        multiple += len(readings) > 1
        for reading, _ in readings:
            tags.update(re.findall(r"<([^<>]+)>", reading))
    return {"types_examined": len(selected), "recognized_types": recognized, "multiple_reading_types": multiple,
            "analyzer_tags": sorted(tags), "adjudicated_analyses": 0}
